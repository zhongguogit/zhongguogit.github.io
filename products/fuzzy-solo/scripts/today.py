def where(day):
    for num, name, until in STAGES:
        if day <= until:
            return num, name, until
    return 6, "收到钱", 30

def light(day):
    # 无历史数据时按"本周是否踩到休整日"给中性判断
    return "🟢 在动" if day % 7 not in (0,) else "🟡 缓了"

