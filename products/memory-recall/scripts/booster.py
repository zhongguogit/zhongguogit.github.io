def _terms(q):
    """把 query 拆成可匹配的词：整体 + 2-4 字滑窗（去掉疑问词）"""
    q = re.sub(r"[怎么|如何|怎样|什么|能不能|可以|要|我想|帮我|请问|？?，,。\s]", "", q)
    terms = {q} if len(q) >= 2 else set()
    for n in (4, 3, 2):
        for i in range(0, max(0, len(q) - n + 1)):
            w = q[i:i+n]
            if len(w) >= 2: terms.add(w)
    STOP = {"怎么", "什么", "可以", "这个", "那个", "一个", "现在", "时候"}
    return {t for t in terms if t not in STOP}


