def main():
    ap = argparse.ArgumentParser(description="加速器：卡住时弹案例")
    ap.add_argument("query", nargs="?", help="你卡在哪（原话）")
    ap.add_argument("--n", type=int, default=2, help="弹几条历史案例")
    ap.add_argument("--script", action="store_true", help="输出连读的语音稿")
    ap.add_argument("--save", dest="save_line", help="把成功的一句存成案例")
