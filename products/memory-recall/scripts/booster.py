def cmd_card(a):
    q = a.query
    bad, alt = check_forbidden(q)
    if bad:
        print(f"⚡ 卡在「{q}」\n")
        print("⛔ 这条我不能给你话术。")
        print(f"   原因：{bad}")
        print()
        print(f"   能给的替代：{alt}。")
        print("   如果你愿意说说真实难处，我帮你找一条合规的说法。")
        return
    od = check_order(q)
    if od:
        print(f"⚡ 卡在「{q}」\n")
        print("⚠️ 这一步顺序不能倒。\n")
        print(f"   你想做的：{od['wrong']}")
        print(f"   正确顺序：{od['right']}")
        print()
        print(f"   倒过来的后果：{od['cost']}")
        print()
        print("   ✅ 最佳方案（目前唯一可行）：")
        print(f"   {od['best']}")
        print()
        print(f"   🔧 唯一能压缩的：{od['can']}")
        print("   ⛔ 不能省的是：顺序本身、以及那个前置的合规文件")
        print()
        print("   ⬆️ 我可以帮你把「加急/并线」的部分做快，但顺序不能改")
        return
    ask = check_ask(q)
    if ask:
        name, steps, risk, why = ask
        print(f"⚡ 卡在「{q}」\n")
        print(f"📋 {name} —— 最佳方案（目前唯一可行）：\n")
        for s in steps:
            print(f"   {s}")
        print()
        print(f"   为什么是唯一可行：{why}")
        print(f"   ⚠️ 最常见错法：{risk}")
        print("   ⬆️ 卡在第几步就说「第N步怎么做」，我给你照念的话")
        return
    fix = check_fix(q)
    if fix:
        name, steps, why = fix
        print(f"⚡ 卡在「{q}」\n")
        print(f"🔧 已经这样了：{name} —— 最佳补救方案（目前唯一可行）：\n")
        for s in steps:
            print(f"   {s}")
        print()
        print(f"   为什么是唯一可行：{why}")
        print("   ⬆️ 别慌，但今天就得动手；拖下去证据会越来越弱")
        return
    print(f"⚡ 卡在「{q}」\n")

    cases = find_cases(q, a.n)
    if cases:
        for m in cases:
            print(f"🟢 这事你做过（{m['at'][:10]} · {m['id']}）")
            print(f"   当时是这么说的：「{m['L1'].strip()[:60]}」")
            if len(m["L3"]) > 1:
                print(f"   关键词：{' / '.join(m['L3'][:5])}")
            print()
        print("   ⬆️ 把里面的数字换成你现在的情况，直接念")
        print()
    else:
        pass  # 没有案例时，是否提示 🟡 取决于后面是否有通用句式（见下）

    gens = find_generic(q, 3)
    if not gens and not cases:
        # 既没做过、也对不上任何场景 → 先看能不能指路，指不了再老实说
        r = check_route(q)
        if r:
            print(f"🧭 「{r['name']}」这个我不做，但我知道该找谁。\n")
            print(f"   去找：{r['who']}")
            print(f"   一句话这么问：")
            print(f"   「{r['ask']}」")
            print()
            if "持证" in r["who"]:
                print("   ⚠️ 我能帮你整理材料、列问题清单，但不下专业结论。")
                print("      这不是小事，别拿网上的说法替代持证的人。")
            print("   ⬆️ 不用自己琢磨怎么描述——照着上面那句说就行")
            return
        print("🟡 这个我没有你的记录，也不属于我内置的商务场景，也没对上指路表。\n")
        print("   我能做的两件事：")
        print("   ① 你给我一句当时的情况原话，我帮你拆成『能照着念的一句』")
        print("   ② 你说个大概领域（谈价/催款/投诉/文案/合同/合作/办事/招人），我给对应句式")
        print("   ⬆️ 别的我不敢编——编出来的话术你念出去，风险是你的。")
        return
    # 去掉跟已有案例重复的（字面重合 ≥ 50% 就算同一句）
    if cases and gens:
        case_text = "".join(m["L1"] for m in cases)
        def overlap(line):
            ct = set(case_text)
            return sum(1 for ch in set(line) if ch in ct) / max(1, len(set(line)))
        gens = [g for g in gens if overlap(g[1]) < 0.5]
    if not gens:
        # 案例已经完全覆盖，就不用再给通用句
        print("   ⬆️ 照着上面那句念就行，把数字换成你的")
        print("   ⬆️ 念完顺利就说「搞定了」，我存成新版本")
        return
    print("   再补几句，一次说完：\n")
    if not cases:
        print("   （🟡 通用句式，不是你的原话——按你的情况改数字再念）\n")
    for i, (scene, line, edit, blind) in enumerate(gens, 1):
        print(f"   {i}. 「{line}」")
        print(f"      → 改这里：{edit}")
    print()
    if a.script:
        print("   ── 连起来念（语音稿）──")
        print("   " + " ".join(f"「{g[1]}」" for g in gens))
        print()
    print("   ⬆️ 卡在哪句就说「第2句怎么说」，我给你换个说法")
    print("   ⬆️ 念完顺利就说「搞定了」，我存成你的案例（下次直接用你自己的）")


def cmd_save(a):
    db = load(DB, [])
    from mem import tag, summarize, mid
    tags = tag(a.line) + [CASE_TAG] + ([a.scene] if a.scene else [])
    item = {"id": mid(db), "at": now().isoformat(timespec="seconds"),
            "title": f"案例·{a.scene or scene_of(a.line) or '通用'}",
            "L1": a.line, "L2": summarize(a.line), "L3": sorted(set(tags)),
            "level": "重要", "bytes": len(a.line.encode())}
    db.append(item); save(DB, db)
    print(f"🟢 已存成你的案例 · {item['id']}")
    print(f"   原话：{a.line}")
    print(f"   标签：{' / '.join(item['L3'])}")
    print("   下次遇到同类，会先给你这条（带日期），而不是通用句式。")


