def scene_of(text):
    """判断一句话属于哪个场景（命中词最多的那个）"""
    best, bn = None, 0
    for s, keys in SCENE_KEYS.items():
        n = sum(1 for k in keys if k in text)
        if n > bn: best, bn = s, n
    return best if bn else None


def find_cases(query, n=3):
    """从用户自己的历史里找带「案例」标签、且与 query 相关的条目"""
    db = load(DB, [])
    cases = [m for m in db if CASE_TAG in m.get("L3", [])]
    if not cases:
        return []
    terms = _terms(query)
    qs = scene_of(query)
    scored = []
    for m in cases:
        hay = m["L1"] + " " + m["L2"] + " " + " ".join(m["L3"])
        hit = sum(1 for t in terms if t in hay)
        if any(t in m["L3"] for t in terms): hit += 2
        # 同一场景（用户说"佣金"，案例标的是"谈价"）→ 强关联
        ms = scene_of(m["L1"] + " " + " ".join(m["L3"]))
        if qs and ms and qs == ms: hit += 3
        if hit: scored.append((hit, m))
    scored.sort(key=lambda x: (-x[0], x[1]["at"]))
    out, seen = [], set()
    for _, m in scored:
        if m["id"] in seen: continue
        seen.add(m["id"]); out.append(m)
        if len(out) >= n: break
    return out


def find_generic(query, n=3):
    """没有历史时，给通用句式：先按命中的句子，再按同场景补齐（保证能"一次说完"）"""
    hit, scene_hit = [], None
    for sc_i, (scene, keys, line, edit) in enumerate(GENERIC):
        sc = sum(1 for k in keys if k in query)
        if sc:
            hit.append((sc, sc_i, scene, line, edit))
    if not hit:
        return []           # 完全不相关 → 不给，别硬塞商务话术
    hit.sort(key=lambda x: -x[0])
    best_scene = hit[0][2]
    out = [(scene, line, edit, False) for _, _, scene, line, edit in hit[:1]]
    # 同一场景的其他句子补齐（这样才"一次说完"，不用来回问）
    for scene, keys, line, edit in GENERIC:
        if scene == best_scene and all(line != o[1] for o in out):
            out.append((scene, line, edit, False))
        if len(out) >= n: break
    return out[:n]


